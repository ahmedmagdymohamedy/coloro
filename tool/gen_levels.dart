class Grid {
  Grid(this.n, int skyColor) : cells = List.filled(n * n, skyColor);

  final int n;
  final List<int> cells;

  void set(int x, int y, int argb) {
    if (x < 0 || y < 0 || x >= n || y >= n) return;
    cells[y * n + x] = argb;
  }

  int at(int x, int y) =>
      (x < 0 || y < 0 || x >= n || y >= n) ? 0 : cells[y * n + x];

  /// Paints [color] wherever [inside] is true, in normalized [-1,1] coords.
  void fill(bool Function(double nx, double ny) inside, int color) {
    for (var y = 0; y < n; y++) {
      for (var x = 0; x < n; x++) {
        final nx = (x + 0.5) / n * 2 - 1;
        final ny = (y + 0.5) / n * 2 - 1;
        if (inside(nx, ny)) set(x, y, color);
      }
    }
  }

  /// Repaints [from] cells as [to] inside an ellipse — used for shading.
  void shade(double cx, double cy, double rx, double ry, int from, int to) {
    for (var y = 0; y < n; y++) {
      for (var x = 0; x < n; x++) {
        final nx = (x + 0.5) / n * 2 - 1;
        final ny = (y + 0.5) / n * 2 - 1;
        final dx = (nx - cx) / rx, dy = (ny - cy) / ry;
        if (dx * dx + dy * dy <= 1 && at(x, y) == from) set(x, y, to);
      }
    }
  }

  /// Outlines every cell of [target] that touches a different color.
  void outline(int target, int color) {
    final snap = List<int>.from(cells);
    int atS(int x, int y) =>
        (x < 0 || y < 0 || x >= n || y >= n) ? target : snap[y * n + x];
    for (var y = 0; y < n; y++) {
      for (var x = 0; x < n; x++) {
        if (atS(x, y) != target) continue;
        if (atS(x - 1, y) != target ||
            atS(x + 1, y) != target ||
            atS(x, y - 1) != target ||
            atS(x, y + 1) != target) {
          set(x, y, color);
        }
      }
    }
  }

  void plus(int x, int y, int color, {int arm = 1}) {
    set(x, y, color);
    for (var k = 1; k <= arm; k++) {
      set(x - k, y, color);
      set(x + k, y, color);
      set(x, y - k, color);
      set(x, y + k, color);
    }
  }

  /// Ring [layer] cells in from the border (0 = outermost).
  void ring(int layer, int color) {
    for (var y = 0; y < n; y++) {
      for (var x = 0; x < n; x++) {
        final r = [x, n - 1 - x, y, n - 1 - y].reduce(math.min);
        if (r == layer) set(x, y, color);
      }
    }
  }

  /// A horizontal band of alternating colors — pure vertical churn.
  void checkerRow(int y, int a, int b, {int period = 1}) {
    for (var x = 0; x < n; x++) {
      set(x, y, (x ~/ period).isEven ? a : b);
    }
  }
}

/// Places a motif inside a sub-region of the grid.
class Zone {
  Zone(this.g, {this.cx = 0, this.cy = 0, this.scale = 1});

  final Grid g;
  final double cx, cy, scale;

  void fill(bool Function(double x, double y) inside, int color) {
    g.fill((nx, ny) => inside((nx - cx) / scale, (ny - cy) / scale), color);
  }
}

