class Scene {
  Scene(this.grid, this.name, this.colorCount);

  final Grid grid;
  final String name;
  final int colorCount;
}

Scene buildScene(LevelSpec spec, {required int seed}) {
  final rnd = math.Random(seed);
  final n = spec.gridSize;
  final pal = palettes[rnd.nextInt(palettes.length)];
  final accents = List<int>.from(pal.accents)..shuffle(rnd);
  final g = Grid(n, pal.skyLow);

  // 1. GRADED SKY — horizontal bands from deep top to bright horizon. Every
  //    column crosses each band, so this alone creates vertical churn.
  // Only two bands: the quantizer merges anything closer than ~52 in
  // perceptual distance, so intermediate gradient steps would vanish.
  final horizon = -0.25 + (rnd.nextDouble() - 0.5) * 0.35;
  g.fill((x, y) => y < horizon, pal.skyTop);
  g.fill((x, y) => y >= horizon, pal.skyLow);

  // 2. GROUND — two tones plus a speckled seam.
  final hasGround = rnd.nextDouble() < 0.55;
  if (hasGround) {
    final groundTop = 0.52 + rnd.nextDouble() * 0.16;
    g.fill((x, y) => y > groundTop, pal.ground);
    g.fill((x, y) => y > groundTop + 0.18, darken(pal.ground, 0.58));
    final seamY = ((groundTop + 1) / 2 * n).floor().clamp(0, n - 1);
    for (var x = 0; x < n; x++) {
      if (rnd.nextDouble() < 0.45) g.set(x, seamY, lighten(pal.ground, 0.55));
    }
  }

  // 3. BACKDROP SCENERY — distant hills behind the subject.
  if (rnd.nextBool()) {
    final hill = accents[6 % accents.length];
    final hy = hasGround ? 0.46 : 0.62;
    for (final hx in [-0.55, 0.15, 0.75]) {
      g.fill((x, y) {
        final dx = (x - hx) / 0.52, dy = (y - hy) / 0.42;
        return dx * dx + dy * dy <= 1 && y < hy;
      }, hill);
    }
  }

  // 4. MAIN MOTIF — shaded light/base/dark/outline plus an accent detail.
  final pool = motifs.where((m) => m.tier <= spec.tier).toList();
  final motif = pool[rnd.nextInt(pool.length)];
  final base = accents[0];
  final ink = Ink(
    lighten(base, 0.55),
    base,
    darken(base, 0.58),
    darken(base, 0.32),
    accents[1],
  );
  final zone = Zone(
    g,
    cy: hasGround ? -0.12 : 0.0,
    scale: 0.58 + spec.t * 0.16,
  );
  motif.draw(zone, ink);

  // 5. SECONDARY MOTIFS — at other heights, so columns cross several
  //    subjects on the way down.
  final minis = spec.hard ? 2 : (spec.t > 0.45 ? 1 : 0);
  for (var k = 0; k < minis; k++) {
    final mini = pool[rnd.nextInt(pool.length)];
    final mBase = accents[(2 + k) % accents.length];
    mini.draw(
      Zone(g, cx: k.isEven ? -0.62 : 0.64, cy: -0.58 + k * 0.16, scale: 0.20),
      Ink(
        lighten(mBase, 0.55),
        mBase,
        darken(mBase, 0.58),
        darken(mBase, 0.32),
        accents[(4 + k) % accents.length],
      ),
    );
  }

  // 6. HARD STRUCTURES — frames gate the bottom rows and checker bands
  //    force alternating colors as the drain reaches them.
  if (spec.hard) {
    g.ring(0, accents[3 % accents.length]);
    if (n >= 24) g.ring(1, accents[4 % accents.length]);
    if (n >= 32) g.ring(2, accents[5 % accents.length]);
    final rowsToCheck = (1 + spec.t * 2).round();
    for (var k = 0; k < rowsToCheck; k++) {
      final y = n - 3 - k * 2;
      if (y > 2) {
        g.checkerRow(
          y,
          accents[(6 + k) % accents.length],
          accents[(7 + k) % accents.length],
          period: 1 + k,
        );
      }
    }
  }

  // 7. BACKGROUND BANDING — the difficulty dial, applied as DESIGN, not
  //    noise: only sky/ground cells are re-tinted, in horizontal bands, so
  //    the subject stays crisp while every column crosses many colors.
  final bgColors = <int>{pal.skyTop, pal.skyLow, pal.ground,
      darken(pal.ground, 0.58), lighten(pal.ground, 0.55)};
  final bandPalette = <int>[
    pal.skyTop,
    pal.skyLow,
    accents[3 % accents.length],
    accents[4 % accents.length],
  ];
  _bandBackground(g, bgColors, bandPalette, spec.churn, rnd);

  // 8. SPARKLE DETAIL — only on open background, so the subject stays
  //    crisp instead of getting speckled.
  final sparkles = 2 + rnd.nextInt(2) + (n ~/ 14);
  final bandColors = {
    pal.skyTop,
    pal.skyLow,
    accents[3 % accents.length],
    accents[4 % accents.length],
  };
  for (var s = 0; s < sparkles; s++) {
    for (var attempt = 0; attempt < 30; attempt++) {
      final x = 2 + rnd.nextInt(n - 4), y = 2 + rnd.nextInt(n - 4);
      var clear = true;
      for (var dy = -1; dy <= 1 && clear; dy++) {
        for (var dx = -1; dx <= 1 && clear; dx++) {
          if (!bandColors.contains(g.at(x + dx, y + dy))) clear = false;
        }
      }
      if (!clear) continue;
      g.plus(x, y, accents[(s + 2) % accents.length], arm: n >= 20 ? 1 : 0);
      break;
    }
  }

  // 9. FAIRNESS PASS — merge anything the quantizer would merge anyway,
  //    cap the palette, top back up to the target with well-separated
  //    accents, then make sure no color is a slot hostage.
  final area = n * n;
  final cap = spec.colorTarget.clamp(5, (5 + area ~/ 90).clamp(5, 12));
  _enforceSeparation(g, 58);
  _capColors(g, cap);
  _topUpColors(g, accents, cap, rnd);
  // Bottom-drain fairness is about COLUMN COVERAGE, not raw cell counts: a
  // color living in only a few columns leaves its bottle starving in a
  // slot while the rest of the board drains. Spread every color across
  // enough columns that its bottle keeps finding work.
  _ensureColumnCoverage(g, 0.55, rnd);


  return Scene(g, motif.name, _tally(g).length);
}

Map<int, int> _tally(Grid g) {
  final counts = <int, int>{};
  for (final c in g.cells) {
    counts[c] = (counts[c] ?? 0) + 1;
  }
  return counts;
}

double _colorDist(int c1, int c2) {
  final dr = ((c1 >> 16 & 0xFF) - (c2 >> 16 & 0xFF)).toDouble();
  final dg = ((c1 >> 8 & 0xFF) - (c2 >> 8 & 0xFF)).toDouble();
  final db = ((c1 & 0xFF) - (c2 & 0xFF)).toDouble();
  return math.sqrt(0.3 * dr * dr + 0.59 * dg * dg + 0.11 * db * db);
}

/// Fraction of vertical neighbour pairs whose color differs.
double gridChurn(Grid g) {
  var changes = 0, pairs = 0;
  for (var x = 0; x < g.n; x++) {
    for (var y = 0; y < g.n - 1; y++) {
      pairs++;
      if (g.at(x, y) != g.at(x, y + 1)) changes++;
    }
  }
  return pairs == 0 ? 0 : changes / pairs;
}

/// Re-tints ONLY background cells (sky/ground) in horizontal bands, at the
/// band period whose resulting vertical churn lands closest to [target].
/// This is what makes late levels hard to drain — every column crosses
/// many colors — while keeping the picture a designed scene rather than
/// static.
void _bandBackground(
  Grid g,
  Set<int> bgColors,
  List<int> bandPalette,
  double target,
  math.Random rnd,
) {
  final original = List<int>.from(g.cells);
  final isBg = [for (final c in original) bgColors.contains(c)];

  List<int> applied(int period, int palLen) {
    final out = List<int>.from(original);
    for (var y = 0; y < g.n; y++) {
      final color = bandPalette[(y ~/ period) % palLen];
      for (var x = 0; x < g.n; x++) {
        final i = y * g.n + x;
        if (isBg[i]) out[i] = color;
      }
    }
    return out;
  }

  var bestCells = original;
  var bestErr = double.infinity;
  for (final period in [1, 2, 3, 4]) {
    for (final palLen in [2, 3, 4]) {
      if (palLen > bandPalette.length) continue;
      final cells = applied(period, palLen);
      g.cells.setAll(0, cells);
      final err = (gridChurn(g) - target).abs();
      if (err < bestErr) {
        bestErr = err;
        bestCells = cells;
      }
    }
  }
  g.cells.setAll(0, bestCells);
}

/// Stamps cells so every color appears in at least [minFraction]/// Stamps cells so every color appears in at least [minFraction] of the
/// columns — the single most important fairness rule for bottom-drain,
/// since a color confined to a few columns starves its bottle.
void _ensureColumnCoverage(Grid g, double minFraction, math.Random rnd) {
  final needColumns = (g.n * minFraction).ceil();
  for (final color in _tally(g).keys.toList()) {
    final present = <int>{};
    for (var x = 0; x < g.n; x++) {
      for (var y = 0; y < g.n; y++) {
        if (g.at(x, y) == color) {
          present.add(x);
          break;
        }
      }
    }
    if (present.length >= needColumns) continue;
    final missing = [
      for (var x = 0; x < g.n; x++)
        if (!present.contains(x)) x,
    ]..shuffle(rnd);
    var toAdd = needColumns - present.length;
    for (final x in missing) {
      if (toAdd <= 0) break;
      // Overwrite a cell of whichever color can spare it most.
      final counts = _tally(g);
      var bestY = -1, bestCount = 0;
      for (var y = 0; y < g.n; y++) {
        final c = counts[g.at(x, y)] ?? 0;
        if (g.at(x, y) != color && c > bestCount) {
          bestCount = c;
          bestY = y;
        }
      }
      if (bestY >= 0) {
        g.set(x, bestY, color);
        toAdd--;
      }
    }
  }
}

/// Merges any pair closer than [minDist] so the runtime quantizer (which
/// merges below ~52) cannot silently collapse the palette under 5.
void _enforceSeparation(Grid g, double minDist) {
  while (true) {
    final counts = _tally(g);
    final colors = counts.keys.toList();
    var mergedAny = false;
    for (var i = 0; i < colors.length && !mergedAny; i++) {
      for (var j = i + 1; j < colors.length; j++) {
        if (_colorDist(colors[i], colors[j]) >= minDist) continue;
        // Keep the more common one.
        final keep =
            counts[colors[i]]! >= counts[colors[j]]! ? colors[i] : colors[j];
        final drop = keep == colors[i] ? colors[j] : colors[i];
        for (var k = 0; k < g.cells.length; k++) {
          if (g.cells[k] == drop) g.cells[k] = keep;
        }
        mergedAny = true;
        break;
      }
    }
    if (!mergedAny) return;
  }
}

/// Adds accent blocks (well separated by construction) until the scene has
/// [target] distinct colors — the campaign's 5-color floor is a hard rule.
void _topUpColors(Grid g, List<int> accents, int target, math.Random rnd) {
  for (final accent in accents) {
    var counts = _tally(g);
    if (counts.length >= target) return;
    if (counts.keys.any((c) => _colorDist(c, accent) < 58)) continue;
    // Stamp a readable patch so the new color is never a slot hostage.
    final need = math.max(10, g.n * g.n ~/ 60);
    var placed = 0, guard = 0;
    while (placed < need && guard++ < 2000) {
      final x = rnd.nextInt(g.n), y = rnd.nextInt(g.n);
      counts = _tally(g);
      if ((counts[g.at(x, y)] ?? 0) > need) {
        g.set(x, y, accent);
        placed++;
      }
    }
  }
}

/// Merges the rarest colors into their nearest kept color until at most
/// [target] distinct colors remain.
void _capColors(Grid g, int target) {
  var counts = _tally(g);
  while (counts.length > target) {
    final rarest =
        counts.entries.reduce((a, b) => a.value <= b.value ? a : b).key;
    var best = rarest;
    var bestD = double.infinity;
    for (final c in counts.keys) {
      if (c == rarest) continue;
      final d = _colorDist(c, rarest);
      if (d < bestD) {
        bestD = d;
        best = c;
      }
    }
    for (var i = 0; i < g.cells.length; i++) {
      if (g.cells[i] == rarest) g.cells[i] = best;
    }
    counts = _tally(g);
  }
}
