class Ink {
  const Ink(this.light, this.base, this.dark, this.outline, this.extra);

  final int light, base, dark, outline, extra;
}

typedef Motif = void Function(Zone z, Ink ink);

void _shadeBlob(Zone z, Ink ink) {
  z.g
    ..shade(z.cx - z.scale * 0.34, z.cy - z.scale * 0.34, z.scale * 0.42,
        z.scale * 0.42, ink.base, ink.light)
    ..shade(z.cx + z.scale * 0.30, z.cy + z.scale * 0.34, z.scale * 0.46,
        z.scale * 0.46, ink.base, ink.dark)
    ..outline(ink.base, ink.outline);
}

void mHeart(Zone z, Ink ink) {
  z.fill((x, y) {
    final xx = x * 1.28, yy = -y * 1.28 + 0.12;
    final a = xx * xx + yy * yy - 1;
    return a * a * a - xx * xx * yy * yy * yy <= 0;
  }, ink.base);
  _shadeBlob(z, ink);
}

void mStar(Zone z, Ink ink) {
  final verts = <math.Point<double>>[];
  for (var i = 0; i < 10; i++) {
    final r = i.isEven ? 0.98 : 0.44;
    final a = -math.pi / 2 + i * math.pi / 5;
    verts.add(math.Point(r * math.cos(a), r * math.sin(a) + 0.04));
  }
  z.fill((x, y) {
    var inside = false;
    for (var i = 0, j = verts.length - 1; i < verts.length; j = i++) {
      final a = verts[i], b = verts[j];
      if ((a.y > y) != (b.y > y) &&
          x < (b.x - a.x) * (y - a.y) / (b.y - a.y) + a.x) {
        inside = !inside;
      }
    }
    return inside;
  }, ink.base);
  _shadeBlob(z, ink);
}

void mMoon(Zone z, Ink ink) {
  z.fill((x, y) {
    final d1 = (x + 0.10) * (x + 0.10) + (y - 0.02) * (y - 0.02);
    final d2 = (x - 0.42) * (x - 0.42) + (y + 0.22) * (y + 0.22);
    return d1 <= 0.92 * 0.92 && d2 > 0.78 * 0.78;
  }, ink.base);
  z.fill((x, y) {
    final d1 = (x + 0.10) * (x + 0.10) + (y - 0.02) * (y - 0.02);
    final d2 = (x - 0.42) * (x - 0.42) + (y + 0.22) * (y + 0.22);
    return d1 <= 0.92 * 0.92 && d2 > 0.78 * 0.78 && d2 <= 1.05 * 1.05;
  }, ink.light);
  z.g.outline(ink.base, ink.outline);
}

void mFlower(Zone z, Ink ink) {
  for (var k = 0; k < 6; k++) {
    final ang = k * math.pi / 3;
    final px = 0.56 * math.cos(ang), py = 0.56 * math.sin(ang);
    z.fill((x, y) {
      final dx = x - px, dy = y - py;
      return dx * dx + dy * dy <= 0.37 * 0.37;
    }, ink.base);
  }
  _shadeBlob(z, ink);
  z.fill((x, y) => x * x + y * y <= 0.30 * 0.30, ink.extra);
}

void mBalloon(Zone z, Ink ink) {
  z.fill((x, y) {
    final dy = (y + 0.24) / 1.10;
    return x * x + dy * dy <= 0.54 * 0.54;
  }, ink.base);
  _shadeBlob(z, ink);
  z.fill(
    (x, y) => y > 0.36 && y < 0.88 && (x - math.sin(y * 6) * 0.06).abs() < 0.045,
    ink.outline,
  );
}

void mSun(Zone z, Ink ink) {
  for (var k = 0; k < 8; k++) {
    final a = k * math.pi / 4;
    final px = 0.80 * math.cos(a), py = 0.80 * math.sin(a);
    z.fill((x, y) {
      final dx = x - px, dy = y - py;
      return dx * dx + dy * dy <= 0.17 * 0.17;
    }, ink.extra);
  }
  z.fill((x, y) => x * x + y * y <= 0.56 * 0.56, ink.base);
  _shadeBlob(z, ink);
}

void mDiamond(Zone z, Ink ink) {
  z.fill((x, y) {
    if (y < -0.26) {
      return y >= -0.62 && x.abs() <= 0.66 * (1 - (-y - 0.26) / 0.36 * 0.45);
    }
    return y <= 0.86 && x.abs() <= 0.66 * (1 - (y + 0.26) / 1.12);
  }, ink.base);
  z.fill((x, y) => y >= -0.62 && y < -0.26 && x.abs() < 0.20, ink.light);
  z.fill((x, y) => y > -0.26 && y < 0.86 && x > 0.10 && x < 0.42, ink.dark);
  z.g.outline(ink.base, ink.outline);
}

void mApple(Zone z, Ink ink) {
  z.fill((x, y) {
    final dy = (y - 0.10) / 1.04;
    return x * x + dy * dy <= 0.56 * 0.56;
  }, ink.base);
  _shadeBlob(z, ink);
  z.fill((x, y) => x.abs() < 0.055 && y > -0.82 && y < -0.44, ink.outline);
  z.fill((x, y) {
    final dx = (x - 0.26) / 0.22, dy = (y + 0.70) / 0.12;
    return dx * dx + dy * dy <= 1;
  }, ink.extra);
}

void mGhost(Zone z, Ink ink) {
  z.fill((x, y) {
    if (y < -0.14) {
      final dy = (y + 0.14) / 0.76;
      return x * x + dy * dy * 0.55 <= 0.56 * 0.56;
    }
    if (y > 0.62) return false;
    return x.abs() <= 0.56 && math.sin((x + 1) * 9) * 0.08 + 0.54 > y;
  }, ink.base);
  _shadeBlob(z, ink);
  for (final ex in [-0.21, 0.21]) {
    z.fill((x, y) {
      final dx = x - ex, dy = y + 0.24;
      return dx * dx + dy * dy <= 0.10 * 0.10;
    }, ink.outline);
  }
}

void mTree(Zone z, Ink ink) {
  for (var layer = 0; layer < 3; layer++) {
    final top = -0.86 + layer * 0.38;
    z.fill((x, y) {
      if (y < top || y > top + 0.54) return false;
      final t = (y - top) / 0.54;
      return x.abs() <= 0.30 + t * 0.44 - layer * 0.02;
    }, layer.isEven ? ink.base : ink.dark);
  }
  z.fill((x, y) => y > 0.54 && y < 0.92 && x.abs() < 0.13, ink.extra);
  z.g.outline(ink.base, ink.outline);
}

void mHouse(Zone z, Ink ink) {
  z.fill((x, y) => y > -0.16 && y < 0.74 && x.abs() < 0.62, ink.base);
  z.fill((x, y) {
    if (y < -0.74 || y > -0.16) return false;
    return x.abs() <= 0.76 * ((y + 0.74) / 0.58);
  }, ink.extra);
  z.fill((x, y) => y > 0.10 && y < 0.50 && (x - 0.24).abs() < 0.16, ink.light);
  z.fill((x, y) => y > 0.24 && y < 0.74 && (x + 0.26).abs() < 0.15, ink.dark);
  z.g.outline(ink.base, ink.outline);
}

void mRocket(Zone z, Ink ink) {
  z.fill((x, y) => y >= -0.54 && y <= 0.36 && x.abs() <= 0.27, ink.base);
  z.fill((x, y) {
    if (y < -0.88 || y > -0.50) return false;
    return x.abs() <= 0.29 * ((y + 0.88) / 0.38);
  }, ink.extra);
  z.fill((x, y) {
    if (y < 0.04 || y > 0.46) return false;
    final t = (y - 0.04) / 0.42;
    return x.abs() >= 0.23 && x.abs() <= 0.23 + 0.31 * t;
  }, ink.extra);
  z.fill((x, y) {
    final dy = y + 0.28;
    return x * x + dy * dy <= 0.16 * 0.16;
  }, ink.light);
  z.fill((x, y) {
    if (y < 0.42 || y > 0.84) return false;
    return x.abs() <= 0.18 * (1 - (y - 0.42) / 0.42);
  }, ink.dark);
  z.g.outline(ink.base, ink.outline);
}

void mFish(Zone z, Ink ink) {
  z.fill((x, y) {
    final dx = (x - 0.10) / 0.64, dy = y / 0.44;
    return dx * dx + dy * dy <= 1;
  }, ink.base);
  z.fill(
    (x, y) => x < -0.44 && x > -0.88 && y.abs() < (x + 0.88) * 0.9,
    ink.dark,
  );
  _shadeBlob(z, ink);
  z.fill((x, y) {
    final dx = x - 0.44, dy = y + 0.10;
    return dx * dx + dy * dy <= 0.08 * 0.08;
  }, ink.extra);
}

void mButterfly(Zone z, Ink ink) {
  for (final side in [-1.0, 1.0]) {
    z.fill((x, y) {
      final dx = x - side * 0.40, dy = y + 0.22;
      return dx * dx + dy * dy <= 0.38 * 0.38;
    }, ink.base);
    z.fill((x, y) {
      final dx = x - side * 0.33, dy = y - 0.28;
      return dx * dx + dy * dy <= 0.30 * 0.30;
    }, ink.extra);
  }
  z.g.outline(ink.base, ink.outline);
  z.fill((x, y) => x.abs() < 0.075 && y > -0.56 && y < 0.56, ink.dark);
}

void mMushroom(Zone z, Ink ink) {
  z.fill((x, y) {
    if (y > 0.06 || y < -0.66) return false;
    return x * x + (y + 0.10) * (y + 0.10) * 2.2 <= 0.80;
  }, ink.base);
  z.fill((x, y) => y > 0.06 && y < 0.64 && x.abs() < 0.23, ink.light);
  for (final d in [
    [-0.36, -0.30],
    [0.29, -0.38],
    [0.0, -0.12],
  ]) {
    z.fill((x, y) {
      final dx = x - d[0], dy = y - d[1];
      return dx * dx + dy * dy <= 0.12 * 0.12;
    }, ink.extra);
  }
  z.g.outline(ink.base, ink.outline);
}

void mCat(Zone z, Ink ink) {
  z.fill((x, y) {
    final dy = (y - 0.10) / 0.86;
    return x * x + dy * dy <= 0.58 * 0.58;
  }, ink.base);
  for (final side in [-1.0, 1.0]) {
    z.fill((x, y) {
      if (y > -0.34 || y < -0.86) return false;
      final t = (y + 0.86) / 0.52;
      return (x - side * 0.36).abs() <= 0.22 * t;
    }, ink.base);
  }
  _shadeBlob(z, ink);
  for (final ex in [-0.22, 0.22]) {
    z.fill((x, y) {
      final dx = x - ex, dy = y - 0.02;
      return dx * dx + dy * dy <= 0.10 * 0.10;
    }, ink.extra);
  }
}

void mCrown(Zone z, Ink ink) {
  z.fill((x, y) => y > 0.06 && y < 0.60 && x.abs() < 0.72, ink.base);
  for (final px in [-0.56, 0.0, 0.56]) {
    z.fill((x, y) {
      if (y < -0.62 || y > 0.10) return false;
      return (x - px).abs() <= 0.22 * ((y + 0.62) / 0.72);
    }, ink.base);
  }
  _shadeBlob(z, ink);
  for (final px in [-0.40, 0.0, 0.40]) {
    z.fill((x, y) {
      final dx = x - px, dy = y - 0.30;
      return dx * dx + dy * dy <= 0.10 * 0.10;
    }, ink.extra);
  }
}

