int darken(int c, [double f = 0.68]) {
  int m(int v) => (v * f).round().clamp(0, 255);
  return 0xFF000000 |
      (m(c >> 16 & 0xFF) << 16) |
      (m(c >> 8 & 0xFF) << 8) |
      m(c & 0xFF);
}

int lighten(int c, [double f = 0.42]) {
  int m(int v) => (v + (255 - v) * f).round().clamp(0, 255);
  return 0xFF000000 |
      (m(c >> 16 & 0xFF) << 16) |
      (m(c >> 8 & 0xFF) << 8) |
      m(c & 0xFF);
}

int mixColor(int a, int b, double f) {
  int m(int x, int y) => (x + (y - x) * f).round().clamp(0, 255);
  return 0xFF000000 |
      (m(a >> 16 & 0xFF, b >> 16 & 0xFF) << 16) |
      (m(a >> 8 & 0xFF, b >> 8 & 0xFF) << 8) |
      m(a & 0xFF, b & 0xFF);
}

/// A themed scene palette: a sky graded from top to horizon, ground tones,
/// and accents that are GUARANTEED mutually distinct — anything closer
/// than the quantizer's merge distance would silently collapse the
/// palette and flatten the difficulty.
class Palette {
  Palette(this.name, this.skyTop, this.skyLow, this.ground, this.hueOffset)
      : accents = _separatedAccents(hueOffset, [skyTop, skyLow, ground]);

  final String name;
  final int skyTop;
  final int skyLow;
  final int ground;
  final double hueOffset;
  final List<int> accents;
}

int _hsl(double h, double s, double l) {
  h = (h % 360 + 360) % 360;
  final c = (1 - (2 * l - 1).abs()) * s;
  final x = c * (1 - ((h / 60) % 2 - 1).abs());
  final m = l - c / 2;
  double r = 0, g = 0, b = 0;
  if (h < 60) {
    r = c;
    g = x;
  } else if (h < 120) {
    r = x;
    g = c;
  } else if (h < 180) {
    g = c;
    b = x;
  } else if (h < 240) {
    g = x;
    b = c;
  } else if (h < 300) {
    r = x;
    b = c;
  } else {
    r = c;
    b = x;
  }
  int q(double v) => ((v + m) * 255).round().clamp(0, 255);
  return 0xFF000000 | (q(r) << 16) | (q(g) << 8) | q(b);
}

/// Farthest-point sampling over a wide hue × lightness × saturation grid:
/// repeatedly take the candidate that is furthest from everything already
/// chosen. That extracts the most mutually-distinct palette the metric
/// allows, so accents never collapse during quantization.
List<int> _separatedAccents(double hueOffset, List<int> fixed) {
  final candidates = <int>[];
  for (final l in [0.30, 0.44, 0.58, 0.72, 0.86]) {
    for (final sat in [0.90, 0.55]) {
      for (var k = 0; k < 12; k++) {
        candidates.add(_hsl(hueOffset + k * 30.0, sat, l));
      }
    }
  }
  candidates
    ..add(0xFFFDFEFF)
    ..add(0xFF16161F);

  final kept = <int>[];
  while (kept.length < 14) {
    var best = -1;
    var bestMin = 0.0;
    for (final c in candidates) {
      var minD = double.infinity;
      for (final f in fixed) {
        minD = math.min(minD, _colorDist(f, c));
      }
      for (final k in kept) {
        minD = math.min(minD, _colorDist(k, c));
      }
      if (minD > bestMin) {
        bestMin = minD;
        best = c;
      }
    }
    if (best == -1 || bestMin < _minSeparation) break;
    kept.add(best);
  }
  return kept;
}

/// Comfortably above the runtime quantizer's ~52 merge distance.
const _minSeparation = 56.0;

