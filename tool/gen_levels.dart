class LevelSpec {
  const LevelSpec({
    required this.number,
    required this.hard,
    required this.t,
    required this.gridSize,
    required this.colorTarget,
    required this.churn,
    required this.shuffleWindow,
    required this.tier,
  });

  /// Ramps for level [n]. Normal and hard levels ramp on separate tracks.
  factory LevelSpec.forLevel(int n) {
    final hard = n % 5 == 0;
    final double t;
    final int gridSize, colorTarget, shuffleWindow;
    final double churn;
    if (hard) {
      final j = n ~/ 5; // 1..60
      t = (j - 1) / (hardCount - 1);
      gridSize = (20 + t * 20).round();
      colorTarget = (7 + t * 3).round(); // 7 .. 10
      churn = 0.45 + t * 0.25; // busy from the start: 0.45 .. 0.70
      shuffleWindow = (4 + t * 8).round(); // 4 .. 12
    } else {
      final i = n - n ~/ 5; // 1..240
      t = (i - 1) / (normalCount - 1);
      gridSize = (15 + t * 24).round();
      colorTarget = (5 + t * 4).round(); // 5 .. 9
      churn = 0.30 + t * 0.28; // 0.30 .. 0.58
      shuffleWindow = (2 + t * 7).round(); // 2 .. 9
    }
    return LevelSpec(
      number: n,
      hard: hard,
      t: t,
      gridSize: gridSize.clamp(15, 40),
      colorTarget: colorTarget,
      churn: churn,
      shuffleWindow: shuffleWindow,
      tier: t < 0.28 ? 0 : (t < 0.62 ? 1 : 2),
    );
  }

  final int number;
  final bool hard;
  final double t;
  final int gridSize;
  final int colorTarget;

  /// 0..1 — how aggressively the art breaks colors up vertically.
  final double churn;

  /// Target tray displacement (the shipped value may end up lower).
  final int shuffleWindow;

  /// Motif complexity tier: 0 easy, 1 mid, 2 advanced.
  final int tier;
}

class BuiltLevel {
  BuiltLevel({
    required this.scene,
    required this.colorCount,
    required this.churn,
    required this.shuffleWindow,
    required this.dealSeed,
    required this.bottleCount,
    required this.attempts,
  });

  final Scene scene;
  final int colorCount;
  final double churn;
  final int shuffleWindow;
  final int dealSeed;
  final int bottleCount;
  final int attempts;
}

/// Builds a scene, then searches for the strongest tray shuffle the real
/// solver can still beat — falling back through weaker shuffles and then
/// fresh scenes, so every level ships proven-winnable.
BuiltLevel _buildLevel(LevelSpec spec) {
  var attempts = 0;
  for (var sceneTry = 0; sceneTry < 24; sceneTry++) {
    // Ease the colour target only after several scenes have failed — the
    // ceiling is what 5 slots can actually juggle.
    final easedSpec = sceneTry < 12
        ? spec
        : LevelSpec(
            number: spec.number,
            hard: spec.hard,
            t: spec.t,
            gridSize: spec.gridSize,
            colorTarget: math.max(5, spec.colorTarget - (sceneTry - 11)),
            churn: spec.churn,
            shuffleWindow: spec.shuffleWindow,
            tier: spec.tier,
          );
    final scene =
        buildScene(easedSpec, seed: spec.number * 7919 + sceneTry * 104729);
    final grid = quantizeImage(
      img.decodeImage(_encodePng(scene.grid))!,
      gridSize: spec.gridSize,
      maxColors: scene.colorCount,
    );
    if (grid.palette.length < 5) continue;

    final base = BottleFactory.build(grid, seed: spec.number);
    final bottleCount = base.length;

    // Cheap feasibility gate: if the perfectly-sorted deal cannot be won,
    // no shuffle of it can be either — drop the scene immediately.
    attempts++;
    if (!BottleFactory.isDealSolvable(grid, base, maxNodes: 30000)) continue;

    // Strongest shuffle first — that's the interesting one.
    for (var window = spec.shuffleWindow; window >= 1; window--) {
      final tries = window == 1 ? 1 : 3;
      for (var k = 0; k < tries; k++) {
        attempts++;
        final dealSeed = (spec.number * 977 + k * 7919 + window * 31) % 100000;
        final deal = BottleFactory.build(
          grid,
          seed: spec.number,
          shuffleWindow: window,
          dealSeed: dealSeed,
        );
        if (BottleFactory.isDealSolvable(grid, deal, maxNodes: 35000)) {
          return BuiltLevel(
            scene: scene,
            colorCount: grid.palette.length,
            churn: _churnOf(grid.cells, grid.cols, grid.rows),
            shuffleWindow: window,
            dealSeed: dealSeed,
            bottleCount: bottleCount,
            attempts: attempts,
          );
        }
      }
    }
  }
  stderr.writeln('LEVEL ${spec.number}: no solvable scene found!');
  exit(1);
}

/// Fraction of vertical neighbour pairs whose color changes — the real
/// difficulty signal for bottom-drain.
double _churnOf(List<int> cells, int cols, int rows) {
  var changes = 0, pairs = 0;
  for (var x = 0; x < cols; x++) {
    for (var y = 0; y < rows - 1; y++) {
      pairs++;
      if (cells[y * cols + x] != cells[(y + 1) * cols + x]) changes++;
    }
  }
  return pairs == 0 ? 0 : changes / pairs;
}

Uint8List _encodePng(Grid g) {
  final im = img.Image(width: g.n, height: g.n, numChannels: 4);
  for (var y = 0; y < g.n; y++) {
    for (var x = 0; x < g.n; x++) {
      final c = g.at(x, y);
      im.setPixelRgba(x, y, (c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF, 255);
    }
  }
  return img.encodePng(im);
}

void savePng(String name, Grid g) {
  File('assets/levels/$name').writeAsBytesSync(_encodePng(g));
}

