// Generates the whole campaign: level PNGs + assets/levels/levels.json.
// Run with: dart run tool/gen_levels.dart
//
// 300 levels, 4 normal : 1 hard, both tracks ramped easiest → hardest.
// See docs/LEVEL_DESIGN_RULES.md for the design rule this implements.
//
// Difficulty in bottom-drain is NOT just "more colors" — it is:
//   1. VERTICAL CHURN — how often the color changes walking up a column.
//      [A,A,A,B,B,B] needs two bottles in sequence; [A,B,A,B,A,B] forces
//      constant swapping against only 5 slots.
//   2. TRAY SHUFFLE — how far a bottle sits from where it is needed. The
//      player must park bottles in slots and keep one breathing.
// Both ramp with the level number, and every shipped level carries a
// (shuffleWindow, dealSeed) pair proven solvable by the real slot-limited
// solver in BottleFactory.
import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;
import 'dart:typed_data';

import 'package:coloro/data/bottle_factory.dart';
import 'package:coloro/data/quantizer.dart';
import 'package:image/image.dart' as img;

const totalLevels = 300;
const normalCount = 240;
const hardCount = 60;

void main() {
  Directory('assets/levels').createSync(recursive: true);
  for (final f in Directory('assets/levels').listSync()) {
    if (f is File && RegExp(r'/\d+\.(png|jpg)$').hasMatch(f.path)) {
      f.deleteSync();
    }
  }

  final manifest = <String, Map<String, Object>>{};
  var totalAttempts = 0;

  for (var n = 1; n <= totalLevels; n++) {
    final spec = LevelSpec.forLevel(n);
    final built = _buildLevel(spec);
    totalAttempts += built.attempts;

    savePng('$n.png', built.scene.grid);
    manifest['$n.png'] = {
      'name': built.scene.name,
      'gridSize': spec.gridSize,
      'maxColors': built.colorCount,
      'hard': spec.hard,
      // Everything that defines this level's difficulty, spelled out.
      'colors': built.colorCount,
      'cells': spec.gridSize * spec.gridSize,
      'churn': double.parse(built.churn.toStringAsFixed(2)),
      'shuffleWindow': built.shuffleWindow,
      'dealSeed': built.dealSeed,
      'bottles': built.bottleCount,
    };
    if (n % 25 == 0) stdout.writeln('  … level $n');
  }

  final json = const JsonEncoder.withIndent('  ').convert({
    'comment':
        'Generated by tool/gen_levels.dart — 240 normal + 60 hard levels '
            'interleaved 4:1, ramped easy → hard. Every level ships with a '
            'shuffleWindow/dealSeed pair proven solvable by the slot-limited '
            'solver. Do not edit by hand; see docs/LEVEL_DESIGN_RULES.md.',
    'levels': manifest,
  });
  File('assets/levels/levels.json').writeAsStringSync('$json\n');
  stdout.writeln(
      'Generated $totalLevels levels ($totalAttempts solver checks)');
}

